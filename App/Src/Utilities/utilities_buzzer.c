void play_song(TIM_HandleTypeDef *htim, uint8_t tim_channel) {
    HAL_TIM_PWM_Start(htim, tim_channel);

    // Play the song
    for (uint16_t i = 0; i < sizeof(song)/sizeof(note_t); i++) {
        note_t note = song[i];

        if (note.pitch == MUSIC_END) {
            play_note(htim, tim_channel, 100, MUSIC_REST, 0);
            break;
        } else {
            play_note(htim, tim_channel, note.duration, note.pitch, note.velocity);
        }
    }
    
    play_note(htim, tim_channel, 100, MUSIC_REST, 0);
}

