#ifdef PLAY_BUZZER_RTOS
static ULONG buzzer_ms_to_ticks(uint16_t ms)
{
    ULONG ticks = ((ULONG)ms * TX_TIMER_TICKS_PER_SECOND + 999u) / 1000u;
    return ticks == 0u ? 1u : ticks;
}
#endif

void play_note(TIM_HandleTypeDef *htim, uint8_t tim_channel, uint16_t note_duration, int8_t note_pitch, uint8_t note_velocity) {

    // checks if note is a rest
	if (note_pitch == MUSIC_REST){
		__HAL_TIM_SET_COMPARE(htim, tim_channel, 0);
        #ifdef PLAY_BUZZER_RTOS
        tx_thread_sleep(buzzer_ms_to_ticks(note_duration));
        #endif
        #ifndef PLAY_BUZZER_RTOS
        HAL_Delay(note_duration);
        #endif
		return;
	}

    // converts note_pitch to frequency
    float note_frequency = 440.0 * powf(1.05946309436, note_pitch);

    // converts note_velocity to 
    float note_multiplier = note_velocity/500.0;

	float period;
	uint32_t prescaler = 1;
	float frequency_with_prescaler;
	do {
		frequency_with_prescaler = HAL_RCC_GetSysClockFreq()/prescaler;
		period = frequency_with_prescaler / note_frequency;
		if (period > 65536){
			prescaler *= 2;
		}
		if (prescaler > 65536){
			period = 1000;
			prescaler = 64;
		}

	} while(period > 65536);

	// Set the prescaler and period registers
	htim->Instance->PSC = prescaler - 1;
	htim->Instance->ARR = period - 1;

    // Update the timer configuration

    //HAL_TIM_Base_Init(htim);
    __HAL_TIM_SET_COMPARE(htim, tim_channel, period * note_multiplier);
    #ifdef PLAY_BUZZER_RTOS
    tx_thread_sleep(buzzer_ms_to_ticks(note_duration));
    #endif
    #ifndef PLAY_BUZZER_RTOS
        HAL_Delay(note_duration);
    #endif
}

